const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const source = fs.readFileSync(require('node:path').join(__dirname, '../static/js/moments.js'), 'utf8');
const localStart = source.indexOf('  function localTaskMediaUrl(');
const localEnd = source.indexOf('  async function projectPwaTasks(', localStart);
const helpersStart = source.indexOf('  function isVideoUrl(');
const helpersEnd = source.indexOf('  function loadGlightboxLib(', helpersStart);
assert.ok(localStart > 0 && localEnd > localStart && helpersStart > 0 && helpersEnd > helpersStart);
let id = 0;
const context = vm.createContext({ window: { BLOG_MEDIA_BACKEND: 'github-pages' }, pendingMediaObjectUrls: {}, pendingMediaMimeByUrl: {}, URL: { createObjectURL: () => 'blob:synthetic/' + (++id) } });
vm.runInContext(source.slice(helpersStart, helpersEnd) + source.slice(localStart, localEnd), context);
const file = new File(['synthetic media'], 'clip.mp4', { type: 'video/mp4' });
const urls = context.taskMediaForView({ id: 'task' }, [{ file, fileType: 'video/mp4', operationId: 'op1', url: 'https://pages.test/not-deployed.mp4' }]);
assert.match(urls[0], /^blob:/, 'the local preview stays usable while Pages deploys');
assert.equal(context.isVideoUrl(urls[0]), true, 'blob videos retain their media type');
assert.equal(context.mediaPreviewUrl(urls[0]), urls[0], 'local files never request nonexistent preview blobs');
assert.equal(context.isVideoUrl('https://pages.test/clip.mp4#t=2'), true);
const changed = context.taskMediaForView({ id: 'task' }, [{ file, fileType: 'video/mp4', operationId: 'op2' }]);
assert.notEqual(changed[0], urls[0], 'a coalesced edit gets the new file preview');
console.log('Moment media: local video types, preview URLs, changed files and deployment previews passed.');
